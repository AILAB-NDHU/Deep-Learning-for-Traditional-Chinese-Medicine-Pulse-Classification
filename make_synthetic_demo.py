"""
Generate a SYNTHETIC demonstration dataset.

The study's chart images and beat-level data cannot be shared (IRB107-08-B).
This script fabricates stand-in charts so that every stage of the pipeline can be
executed end-to-end: it draws per-subject three-Gaussian pulse templates for the
three pulse types (the same parametric model the paper uses for feature
extraction, Section III-E), adds heart-rate and amplitude variation and noise,
and renders each 6-s recording to a PNG in the same style as the device export
(same figure size, dpi, line colour and grid as `src/validate_roundtrip.py`).

**These data are not measurements of any person and carry no clinical meaning.**
Results obtained on them demonstrate that the code runs; they say nothing about
pulse classification.

Usage:  python make_synthetic_demo.py [--out data/synthetic_demo/pluse] [--seed 0]
Then:   PULSE_ROOT=data/synthetic_demo/pluse python src/build_dataset.py
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np
from scipy import signal as sp_signal

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT))
from src.validate_roundtrip import render_waveform_to_png, _PULSE_PRESETS  # noqa: E402
from src.features.gaussian_fit import three_gaussian                        # noqa: E402

DURATION_S = 6.0
N_PTS = 3000
# (folder name used by build_dataset.py, subject-id base, number of synthetic subjects)
CLASSES = [("弦脈", 100, 15), ("滑脈", 200, 15), ("緊脈", 300, 10)]


def synth_recording(params, rng, hr_bpm):
    """One 6-s recording: beat template repeated at a slightly varying heart rate."""
    t_beat = np.linspace(0, 1, 200)
    beat = three_gaussian(t_beat, *params)
    beat = beat - beat.min()
    n_beats = int(round(DURATION_S * hr_bpm / 60.0))
    pieces = []
    for _ in range(n_beats):
        stretch = rng.normal(1.0, 0.04)                 # beat-to-beat interval jitter
        amp = rng.normal(1.0, 0.05)                     # respiratory-like amplitude modulation
        n = max(40, int(200 * stretch))
        pieces.append(amp * sp_signal.resample(beat, n))
    sig = np.concatenate(pieces)
    sig = sp_signal.resample(sig, N_PTS)
    sig = sig + 0.02 * np.sin(2 * np.pi * 0.25 * np.linspace(0, DURATION_S, N_PTS))   # slow baseline drift
    sig = sig + rng.normal(0, 0.01, N_PTS)              # sensor noise
    return sig


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(ROOT / "data" / "synthetic_demo" / "pluse"))
    ap.add_argument("--seed", type=int, default=0)
    args = ap.parse_args()
    rng = np.random.default_rng(args.seed)
    out = Path(args.out)
    n_files = 0
    for folder, base_id, n_subj in CLASSES:
        d = out / folder
        d.mkdir(parents=True, exist_ok=True)
        base = np.array(_PULSE_PRESETS[folder])
        for s in range(n_subj):
            sid = base_id + s + 1
            subj_params = base * rng.uniform(0.85, 1.15, size=9)      # subject-specific morphology
            subj_params[[1, 4, 7]] = np.clip(np.sort(subj_params[[1, 4, 7]]), 0.05, 0.95)  # keep mu ordered
            hr = rng.uniform(55, 95)
            for rec in range(int(rng.integers(1, 4))):                # 1-3 recordings per subject
                sig = synth_recording(subj_params, rng, hr * rng.normal(1.0, 0.03))
                render_waveform_to_png(sig, d / f"{sid}_{rec + 1}.png")
                n_files += 1
    (out.parent / "README_SYNTHETIC.txt").write_text(
        "SYNTHETIC DEMONSTRATION DATA.\nThese charts were generated by make_synthetic_demo.py from a parametric\n"
        "three-Gaussian pulse model. They are not measurements of any person and have no clinical meaning.\n"
        "The study data (Hualien Tzu Chi Hospital IRB107-08-B) cannot be shared.\n", encoding="utf-8")
    print(f"wrote {n_files} synthetic chart PNGs under {out}")


if __name__ == "__main__":
    main()
