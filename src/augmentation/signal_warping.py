"""
TCM Pulse — Physical Augmentation for Minority Class (Tight / 緊脈)
====================================================================

Background
----------
Tight pulse has only 163 beats from ~15 subjects (smallest class in the
3-class experiment).  This module applies two physically-motivated
perturbations to inflate the Tight class to a user-specified target count,
while preserving the waveform morphology that gaussian_fit.py relies on.

Augmentation Methods
--------------------
1. **Magnitude Warping**
   A smooth random multiplier curve (generated by Cubic Spline through
   random knot amplitudes ≈ N(1.0, σ)) is element-wise multiplied onto
   the beat.  Simulates beat-to-beat variation in press force / arterial
   compliance.

2. **Jittering**
   Additive Gaussian noise σ_n = √(P_signal / 10^(SNR_db/10)).
   At SNR = 30 dB the noise power is 1/1000 of signal power.

3. **Time Warping**
   The time axis is non-linearly stretched / compressed via a random
   monotonic Cubic Spline mapping.  Beat is re-interpolated at warped
   positions.  Simulates beat-to-beat variability in pulse morphology
   tempo (e.g., faster systolic upstroke, slower diastolic decay).

4. **Window Slicing**
   A random sub-window (85–98 % of the original 200 pts) is extracted
   and FFT-resampled back to 200 pts.  Simulates slight misalignment
   in beat segmentation boundaries — a common real-world artifact.

5. **Mixup**
   Two Tight beats are linearly interpolated: λ·beat_A + (1-λ)·beat_B
   with λ ~ Beta(α, α), clipped to [0.2, 0.8].  Produces morphologies
   that lie on the convex hull of the class, improving decision-boundary
   generalisation for the CNN.

Combination Strategy
--------------------
Each synthetic beat independently draws one of six modes:
  - jitter           (p ≈ 1/6)
  - magnitude_warp   (p ≈ 1/6)
  - both             (p ≈ 1/6)
  - time_warp        (p ≈ 1/6)
  - window_slice     (p ≈ 1/6)
  - mixup            (p ≈ 1/6)

Original beats are preserved unchanged (included in the output).

Outputs (when run as script)
-----------------------------
  outputs/tight_augmented_beats.npy   shape (target_n, 200) float32
  outputs/tight_augmented_meta.csv    per-row metadata

Public API
----------
  augment_tight(beats, df, target_n, seed) → (ndarray, DataFrame)
  magnitude_warp(beat, knot_count, warp_sigma, rng) → ndarray
  jitter(beat, snr_db, rng) → ndarray
  time_warp(beat, knot_count, sigma, rng) → ndarray
  window_slice(beat, slice_ratio_min, slice_ratio_max, rng) → ndarray
  mixup(beat_a, beat_b, alpha, rng) → ndarray
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.interpolate import CubicSpline
from scipy.signal import resample as scipy_resample

ROOT = Path(__file__).parent.parent.parent
sys.path.insert(0, str(ROOT))

# ─────────────────────────────────────────────────────────────────────────────
# Constants
# ─────────────────────────────────────────────────────────────────────────────
_BEAT_LEN     = 200
_TIGHT_EN     = "Tight"
_TARGET_N     = 1500
_DEFAULT_SEED = 42


# ─────────────────────────────────────────────────────────────────────────────
# Core augmentation primitives
# ─────────────────────────────────────────────────────────────────────────────

def magnitude_warp(
    beat: np.ndarray,
    knot_count: int = 4,
    warp_sigma: float = 0.20,
    rng: np.random.Generator | None = None,
) -> np.ndarray:
    """Apply Magnitude Warping to a single beat waveform."""
    if rng is None:
        rng = np.random.default_rng()
    n = len(beat)
    knot_x = np.linspace(0, n - 1, knot_count + 2)
    raw_vals = rng.normal(loc=1.0, scale=warp_sigma, size=len(knot_x))
    knot_y = np.clip(raw_vals, 0.3, 1.7)
    cs = CubicSpline(knot_x, knot_y)
    x_full = np.arange(n, dtype=np.float64)
    warper = cs(x_full)
    warper = np.clip(warper, 0.1, 3.0)
    return beat * warper


def jitter(
    beat: np.ndarray,
    snr_db: float = 32.0,
    rng: np.random.Generator | None = None,
) -> np.ndarray:
    """Apply additive Gaussian jitter at a given SNR level."""
    if rng is None:
        rng = np.random.default_rng()
    beat = np.asarray(beat, dtype=np.float64)
    p_signal = float(np.mean(beat ** 2))
    p_noise  = p_signal / (10.0 ** (snr_db / 10.0))
    sigma_n  = np.sqrt(max(p_noise, 1e-12))
    noise = rng.normal(loc=0.0, scale=sigma_n, size=len(beat))
    return beat + noise


def time_warp(
    beat: np.ndarray,
    knot_count: int = 4,
    sigma: float = 0.20,
    rng: np.random.Generator | None = None,
) -> np.ndarray:
    """Apply Time Warping to a single beat waveform.

    The time axis is non-linearly stretched/compressed by mapping it through
    a random monotonic Cubic Spline, then interpolating the original signal
    at the warped positions.
    """
    if rng is None:
        rng = np.random.default_rng()
    n = len(beat)
    beat = np.asarray(beat, dtype=np.float64)

    knot_x = np.linspace(0, n - 1, knot_count + 2)
    # Positive random increments → cumsum is monotonically increasing
    increments = np.abs(rng.normal(1.0, sigma, size=len(knot_x))) + 1e-6
    knot_y = np.cumsum(increments)
    # Normalize so warped axis spans [0, n-1]
    knot_y = knot_y * (n - 1) / knot_y[-1]
    knot_y[0]  = 0.0
    knot_y[-1] = float(n - 1)

    cs = CubicSpline(knot_x, knot_y)
    x_full   = np.arange(n, dtype=np.float64)
    warped_x = np.clip(cs(x_full), 0.0, n - 1)
    return np.interp(warped_x, x_full, beat)


def window_slice(
    beat: np.ndarray,
    slice_ratio_min: float = 0.85,
    slice_ratio_max: float = 0.98,
    rng: np.random.Generator | None = None,
) -> np.ndarray:
    """Extract a random sub-window and FFT-resample back to original length.

    Simulates slight segmentation boundary jitter: the beat extraction window
    is shifted/shortened, then resampled to restore the fixed 200-pt length.
    """
    if rng is None:
        rng = np.random.default_rng()
    beat = np.asarray(beat, dtype=np.float64)
    n = len(beat)

    ratio     = rng.uniform(slice_ratio_min, slice_ratio_max)
    slice_len = max(int(n * ratio), 4)
    max_start = n - slice_len
    start     = int(rng.integers(0, max(max_start, 1)))
    sliced    = beat[start : start + slice_len]
    return scipy_resample(sliced, n).astype(np.float64)


def mixup(
    beat_a: np.ndarray,
    beat_b: np.ndarray,
    alpha: float = 0.3,
    rng: np.random.Generator | None = None,
) -> np.ndarray:
    """Linearly interpolate two beats of the same class.

    λ ~ Beta(alpha, alpha), clipped to [0.2, 0.8] to avoid near-copies.
    Mixed beat = λ·beat_a + (1-λ)·beat_b.
    """
    if rng is None:
        rng = np.random.default_rng()
    lam = float(rng.beta(alpha, alpha))
    lam = float(np.clip(lam, 0.2, 0.8))
    beat_a = np.asarray(beat_a, dtype=np.float64)
    beat_b = np.asarray(beat_b, dtype=np.float64)
    return lam * beat_a + (1.0 - lam) * beat_b


# ─────────────────────────────────────────────────────────────────────────────
# Augmentation pipeline
# ─────────────────────────────────────────────────────────────────────────────

def augment_tight(
    beats: np.ndarray,
    df: pd.DataFrame,
    target_n: int = _TARGET_N,
    seed: int = _DEFAULT_SEED,
    knot_count: int = 4,
    warp_sigma: float = 0.20,
    snr_db: float = 32.0,
) -> tuple[np.ndarray, pd.DataFrame]:
    """Augment Tight beats from ``beats`` / ``df`` to ``target_n`` samples.

    Original Tight beats are always included unchanged at the start.
    Synthetic beats fill the remainder with random perturbations.

    Parameters
    ----------
    beats : np.ndarray, shape (N_total, beat_len)
        Full beats_matrix.npy (all pulse types).
    df : pd.DataFrame
        Full dataset.csv aligned row-by-row with *beats*.
    target_n : int
        Final count of Tight beats (original + synthetic).
    seed : int
        Random seed for reproducibility.
    """
    rng = np.random.default_rng(seed)

    tight_mask = (df["pulse_type_en"] == _TIGHT_EN).values
    tight_idx  = np.where(tight_mask)[0]
    n_original = len(tight_idx)

    if n_original == 0:
        raise ValueError("No Tight beats found in dataset.csv")
    if target_n < n_original:
        raise ValueError(f"target_n={target_n} < n_original={n_original}")

    print(f"[augment_tight]  original={n_original}  target={target_n}  "
          f"synthetic={target_n - n_original}")

    n_synthetic = target_n - n_original
    mode_names  = {
        0: "jitter",
        1: "magnitude_warp",
        2: "both",
        3: "time_warp",
        4: "window_slice",
        5: "mixup",
    }

    aug_beats: list[np.ndarray] = []
    meta_rows: list[dict]       = []

    # ── 1. Keep all originals ─────────────────────────────────────────────────
    for local_i, src_i in enumerate(tight_idx):
        aug_beats.append(beats[src_i].astype(np.float64))
        meta_rows.append({
            "row_idx":         local_i,
            "source_row":      int(src_i),
            "subject_id":      df.iloc[src_i]["subject_id"],
            "pulse_type_en":   _TIGHT_EN,
            "aug_mode":        "original",
            "fit_r2_original": df.iloc[src_i].get("fit_r2", float("nan")),
        })

    # ── 2. Generate synthetic beats ───────────────────────────────────────────
    src_choices  = rng.integers(0, n_original, size=n_synthetic)
    src_choices2 = rng.integers(0, n_original, size=n_synthetic)  # for mixup
    mode_choices = rng.integers(0, 6, size=n_synthetic)

    for syn_i in range(n_synthetic):
        src_local = src_choices[syn_i]
        src_row   = tight_idx[src_local]
        base_beat = beats[src_row].astype(np.float64).copy()
        mode      = int(mode_choices[syn_i])

        if mode == 0:
            out = jitter(base_beat, snr_db=snr_db, rng=rng)
        elif mode == 1:
            out = magnitude_warp(base_beat, knot_count=knot_count,
                                 warp_sigma=warp_sigma, rng=rng)
        elif mode == 2:
            out = magnitude_warp(base_beat, knot_count=knot_count,
                                 warp_sigma=warp_sigma, rng=rng)
            out = jitter(out, snr_db=snr_db, rng=rng)
        elif mode == 3:
            out = time_warp(base_beat, knot_count=knot_count,
                            sigma=warp_sigma, rng=rng)
        elif mode == 4:
            out = window_slice(base_beat, rng=rng)
        else:  # mode == 5: mixup
            src_row2 = tight_idx[src_choices2[syn_i]]
            beat_b   = beats[src_row2].astype(np.float64)
            out      = mixup(base_beat, beat_b, rng=rng)

        aug_beats.append(out)
        meta_rows.append({
            "row_idx":         n_original + syn_i,
            "source_row":      int(src_row),
            "subject_id":      df.iloc[src_row]["subject_id"],
            "pulse_type_en":   _TIGHT_EN,
            "aug_mode":        mode_names[mode],
            "fit_r2_original": df.iloc[src_row].get("fit_r2", float("nan")),
        })

    aug_array = np.stack(aug_beats, axis=0).astype(np.float32)
    meta_df   = pd.DataFrame(meta_rows)
    return aug_array, meta_df


# ─────────────────────────────────────────────────────────────────────────────
# Validation helper
# ─────────────────────────────────────────────────────────────────────────────

def validate_snr(original: np.ndarray, augmented: np.ndarray) -> float:
    p_signal = float(np.mean(original.astype(np.float64) ** 2))
    p_noise  = float(np.mean((augmented.astype(np.float64)
                               - original.astype(np.float64)) ** 2))
    if p_noise < 1e-15:
        return float("inf")
    return 10.0 * np.log10(p_signal / p_noise)


# ─────────────────────────────────────────────────────────────────────────────
# Script entry point
# ─────────────────────────────────────────────────────────────────────────────

def main() -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from src.features.gaussian_fit import fit_three_gaussians

    OUT = ROOT / "outputs"

    print("Loading data …")
    beats = np.load(OUT / "beats_matrix.npy")
    df    = pd.read_csv(OUT / "dataset.csv")
    assert len(beats) == len(df), "beats_matrix and dataset.csv row count mismatch"

    n_tight_orig = (df["pulse_type_en"] == _TIGHT_EN).sum()
    print(f"Original Tight beats : {n_tight_orig}")
    print(f"Target count         : {_TARGET_N}")

    aug_beats, meta = augment_tight(
        beats, df, target_n=_TARGET_N, seed=_DEFAULT_SEED
    )

    # ── Verify SNR on jitter-only samples ─────────────────────────────────────
    jitter_rows = meta[meta["aug_mode"] == "jitter"].head(20)
    snr_values  = []
    for _, row in jitter_rows.iterrows():
        src = beats[int(row["source_row"])].astype(np.float64)
        aug = aug_beats[int(row["row_idx"])].astype(np.float64)
        snr_values.append(validate_snr(src, aug))
    print(f"\nJitter SNR check (first 20 samples):  mean={np.mean(snr_values):.1f} dB"
          f"  min={np.min(snr_values):.1f} dB  (spec: >30 dB)")
    assert np.min(snr_values) > 30.0, "⚠ SNR constraint violated!"

    # ── Re-fit Gaussians on ALL augmented beats ───────────────────────────────
    print("\nRe-fitting 3-Gaussian on augmented beats …")
    n_total      = len(aug_beats)
    r2_list      = []
    fail_cnt     = 0
    feature_cols = ["A1","mu1","sigma1","A2","mu2","sigma2","A3","mu3","sigma3"]
    feat_rows: list[dict] = []

    for i, beat in enumerate(aug_beats):
        if i % 300 == 0:
            print(f"  {i}/{n_total}", flush=True)
        params, converged, r2 = fit_three_gaussians(beat.astype(np.float64))
        if params is not None:
            r2_list.append(r2)
            feat_rows.append(dict(zip(feature_cols, params.tolist())) | {"fit_r2": r2, "converged": True})
        else:
            fail_cnt += 1
            feat_rows.append({c: float("nan") for c in feature_cols} | {"fit_r2": float("nan"), "converged": False})

    meta_full = pd.concat(
        [meta.reset_index(drop=True), pd.DataFrame(feat_rows)], axis=1
    )

    print(f"\n  Fit failures : {fail_cnt} / {n_total}  ({100*fail_cnt/n_total:.1f}%)")
    print(f"  Mean R²      : {np.nanmean(r2_list):.4f}")
    print(f"  Min  R²      : {np.nanmin(r2_list):.4f}")

    print("\nAugmentation mode distribution:")
    print(meta["aug_mode"].value_counts().to_string())

    # ── Save outputs ──────────────────────────────────────────────────────────
    npy_path  = OUT / "tight_augmented_beats.npy"
    meta_path = OUT / "tight_augmented_meta.csv"

    np.save(npy_path, aug_beats)
    meta_full.to_csv(meta_path, index=False, float_format="%.6f")

    print(f"\n  Saved → outputs/tight_augmented_beats.npy  {aug_beats.shape}  {aug_beats.dtype}")
    print(f"  Saved → outputs/tight_augmented_meta.csv   {meta_full.shape}")

    # ── Quick visualisation ───────────────────────────────────────────────────
    fig, axes = plt.subplots(2, 4, figsize=(14, 5))
    tight_orig_idx = meta[meta["aug_mode"] == "original"]["row_idx"].values[:4]
    aug_idx        = meta[meta["aug_mode"] != "original"]["row_idx"].values[:4]

    for col, idx in enumerate(tight_orig_idx[:4]):
        axes[0, col].plot(aug_beats[idx], color="#2ca02c", lw=1.2)
        axes[0, col].set_title(f"Original #{col}", fontsize=12)
        axes[0, col].set_ylim(-3, 3)
        axes[0, col].axis("off")

    for col, idx in enumerate(aug_idx[:4]):
        mode = meta.iloc[idx]["aug_mode"]
        src  = int(meta.iloc[idx]["source_row"])
        axes[1, col].plot(beats[src], color="#aaaaaa", lw=1, label="orig")
        axes[1, col].plot(aug_beats[idx], color="#d62728", lw=1.2, label=mode)
        axes[1, col].set_title(mode, fontsize=12)
        axes[1, col].set_ylim(-3, 3)
        axes[1, col].legend(fontsize=10)
        axes[1, col].axis("off")

    fig.suptitle("Tight pulse: waveform-level augmentation samples", fontsize=13, fontweight="bold")
    fig.tight_layout()
    fig_path = OUT / "tight_augmentation_samples.png"
    fig.savefig(fig_path, dpi=300)
    fig.savefig(fig_path.with_suffix(".pdf"))
    plt.close(fig)
    print(f"  Saved → outputs/tight_augmentation_samples.png")
    print("\nPhase 5 (Tight augmentation) DONE")


if __name__ == "__main__":
    main()
